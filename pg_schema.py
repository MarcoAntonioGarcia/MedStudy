#!/usr/bin/env python3
"""Genera el esquema de PostgreSQL a partir de SCHEMA.sql (portado de EnglishApp).

SCHEMA.sql sigue siendo la ÚNICA fuente del esquema: mantener a mano un segundo
archivo en dialecto Postgres sería garantizar que un día dejen de coincidir.
La app lo aplica sola al arrancar contra Postgres (core.DatabaseManager); este
script solo sirve para mirarlo.

    python pg_schema.py            # lo imprime
    python pg_schema.py --check    # avisa de lo que no sabe traducir
"""
from __future__ import annotations

import re
import sys

import core

# Lo que cambia en el DDL entre los dos motores.
#   AUTOINCREMENT  -> IDENTITY (el estándar; SERIAL es la forma antigua)
#   REAL           -> DOUBLE PRECISION (REAL en Postgres es de 4 bytes)
#   COLLATE NOCASE -> no existe: la unicidad sin mayúsculas va en un índice
#                     sobre lower(columna)
#   datetime('now')-> lo traduce core.a_postgres (texto UTC, como SQLite)
_TIPOS = (
    (r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
     "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (r"\bREAL\b", "DOUBLE PRECISION"),
    (r"\s+COLLATE\s+NOCASE", ""),
)

# Columnas que en SQLite son COLLATE NOCASE y UNIQUE: sin este índice,
# 'Ana@x.com' y 'ana@x.com' serían dos cuentas distintas en Postgres.
_SIN_MAYUSCULAS = {"users": ("username", "email")}

_RE_TABLA = re.compile(r"CREATE TABLE IF NOT EXISTS (\w+)\s*\((.*?)\n\);", re.S)
# UNIQUE también: el índice único parcial de cards (anki_guid, cloze_index) es
# el que impide duplicar fichas al reimportar.
_RE_INDICE = re.compile(r"CREATE (?:UNIQUE )?INDEX IF NOT EXISTS .*?;", re.S)
_RE_RESTRICCION = re.compile(r"(PRIMARY KEY|FOREIGN KEY|UNIQUE|CHECK)\b", re.I)


def _sin_comentarios(texto: str) -> str:
    """Quita los comentarios '--'. En SCHEMA.sql no hay '--' dentro de cadenas, y
    un '?' o un '%' en un comentario confundiría a psycopg con una marca."""
    return re.sub(r"--[^\n]*", "", texto)


def _leer() -> str:
    with open(core.SCHEMA_PATH, "r", encoding="utf-8") as fh:
        return _sin_comentarios(fh.read())


def _traducir(ddl: str) -> str:
    for patron, nuevo in _TIPOS:
        ddl = re.sub(patron, nuevo, ddl, flags=re.I)
    return core.a_postgres(ddl)


def sentencias_tablas() -> list[str]:
    """CREATE TABLE de cada tabla, en el orden de SCHEMA.sql (respeta las
    claves ajenas), y los índices de unicidad sin mayúsculas."""
    fuera = []
    for m in _RE_TABLA.finditer(_leer()):
        tabla = m.group(1)
        cuerpo = "\n".join(l.rstrip() for l in m.group(0).split("\n") if l.strip())
        fuera.append(_traducir(cuerpo).rstrip(";"))
        for col in _SIN_MAYUSCULAS.get(tabla, ()):
            fuera.append(f"CREATE UNIQUE INDEX IF NOT EXISTS idx_{tabla}_{col}_lower "
                         f"ON {tabla} (lower({col}))")
    return fuera


def sentencias_indices() -> list[str]:
    return [_traducir(re.sub(r"\s+", " ", m.group(0))).rstrip(";")
            for m in _RE_INDICE.finditer(_leer())]


def sentencias() -> list[str]:
    return sentencias_tablas() + sentencias_indices()


def columnas_por_tabla() -> list[tuple[str, list[tuple[str, str]]]]:
    """[(tabla, [(columna, definición en Postgres), …])] según SCHEMA.sql.
    Lo usa core para añadir a una base ya creada las columnas nuevas."""
    fuera = []
    for m in _RE_TABLA.finditer(_leer()):
        columnas = []
        for linea in m.group(2).split("\n"):
            linea = linea.strip().rstrip(",")
            if not linea or _RE_RESTRICCION.match(linea):
                continue
            partes = linea.split(None, 1)
            if len(partes) == 2:
                columnas.append((partes[0], _traducir(partes[1])))
        fuera.append((m.group(1), columnas))
    return fuera


def generar() -> str:
    return ("-- GENERADO por pg_schema.py desde SCHEMA.sql. No editar a mano.\n"
            + ";\n\n".join(sentencias()) + ";\n")


def comprobar() -> list[str]:
    """Restos de dialecto SQLite en el DDL traducido (vacío = ninguno)."""
    problemas = []
    for s in sentencias():
        problemas += [f"{aviso}: {s[:60]}" for aviso in core.problemas_postgres(s)]
        if not re.match(r"CREATE (TABLE|INDEX|UNIQUE INDEX) IF NOT EXISTS", s):
            problemas.append("sentencia rara: " + s[:60])
    return problemas


if __name__ == "__main__":
    if "--check" in sys.argv:
        problemas = comprobar()
        for p in problemas:
            print("SIN TRADUCIR: " + p, file=sys.stderr)
        print("tablas: %d  |  índices: %d" % (len(list(_RE_TABLA.finditer(_leer()))),
                                              len(sentencias_indices())))
        raise SystemExit(1 if problemas else 0)
    print(generar())
